static esp_err_t redetect_post(httpd_req_t *req)
{
    if (on_ap(req)) {
        return to_setup_page(req);
    }
    if (!same_origin(req)) {
        return cross_site(req);
    }
    printer_link_request_redetect();
    return redirect_home(req);
}

static esp_err_t forget_post(httpd_req_t *req)
{
    if (on_ap(req)) {
        return to_setup_page(req);
    }
    if (!same_origin(req)) {
        return cross_site(req);
    }
    settings_clear_wifi();
    ESP_LOGW(TAG, "WiFi credentials cleared from the web page, rebooting");
    httpd_resp_sendstr(req, "WiFi forgotten. Rebooting into setup mode.");
    restart_soon();
    return ESP_OK;
}

/* Captive portal: any unknown URL asked over the setup AP goes to the setup page. */
static esp_err_t not_found(httpd_req_t *req, httpd_err_code_t err)
{
    (void)err;
    if (on_ap(req)) {
        return to_setup_page(req);
    }
    return httpd_resp_send_err(req, HTTPD_404_NOT_FOUND, "not found");
}

void web_start(void)
{
    httpd_config_t cfg = HTTPD_DEFAULT_CONFIG();
    cfg.max_open_sockets = 4;
    cfg.stack_size = 8192;
    cfg.lru_purge_enable = true;
    cfg.max_uri_handlers = 16;
    httpd_handle_t server;
    if (httpd_start(&server, &cfg) != ESP_OK) {
        ESP_LOGE(TAG, "HTTP server failed to start");
        return;
    }
    const httpd_uri_t uris[] = {
        {.uri = "/", .method = HTTP_GET, .handler = root_get},
        {.uri = "/save", .method = HTTP_POST, .handler = save_post},
        {.uri = "/api/status", .method = HTTP_GET, .handler = status_get},
        {.uri = "/favicon.svg", .method = HTTP_GET, .handler = favicon_get},
        {.uri = "/settings", .method = HTTP_GET, .handler = settings_get_page},
        {.uri = "/config", .method = HTTP_POST, .handler = config_post},
        {.uri = "/redetect", .method = HTTP_POST, .handler = redetect_post},
        {.uri = "/forget", .method = HTTP_POST, .handler = forget_post},
        {.uri = "/api/printer_config", .method = HTTP_GET, .handler = printer_config_get},
        {.uri = "/printer_config", .method = HTTP_POST, .handler = printer_config_post},
        {.uri = "/printer_action", .method = HTTP_POST, .handler = printer_action_post},
    };
    for (size_t i = 0; i < sizeof(uris) / sizeof(uris[0]); i++) {
        esp_err_t err = httpd_register_uri_handler(server, &uris[i]);
        if (err != ESP_OK) {
            ESP_LOGE(TAG, "cannot register %s: %s", uris[i].uri, esp_err_to_name(err));
        }
    }
    httpd_register_err_handler(server, HTTPD_404_NOT_FOUND, not_found);
    ESP_LOGI(TAG, "HTTP server on port 80");
}
