/*
 * Validate Host header to protect against DNS rebinding attacks on the LAN.
 * Captive-portal requests on the setup AP are exempt as phones use arbitrary probe hosts.
 */
static bool host_allowed(httpd_req_t *req)
{
    if (on_ap(req)) {
        return true;
    }
    char host[96];
    if (httpd_req_get_hdr_value_str(req, "Host", host, sizeof(host)) != ESP_OK) {
        return false;
    }
    /* Strip port if present */
    char *colon = strchr(host, ':');
    if (colon != NULL) {
        char *bracket = strrchr(host, ']');
        if (bracket != NULL) {
            colon = strchr(bracket, ':');
        } else if (strchr(colon + 1, ':') != NULL) {
            colon = NULL;
        }
        if (colon != NULL) {
            *colon = '\0';
        }
    }
    if (strcmp(host, "192.168.4.1") == 0) {
        return true;
    }
    char sta_ip[16] = "";
    wifi_prov_ip(sta_ip);
    if (sta_ip[0] != '\0' && strcmp(host, sta_ip) == 0) {
        return true;
    }
    settings_net_t net;
    settings_get_net(&net);
    if (net.hostname[0] != '\0') {
        char local_host[sizeof(net.hostname) + 8];
        snprintf(local_host, sizeof(local_host), "%s.local", net.hostname);
        if (strcasecmp(host, local_host) == 0 || strcasecmp(host, net.hostname) == 0) {
            return true;
        }
    }
    if (strcasecmp(host, "zebserial.local") == 0 || strcasecmp(host, "zebserial") == 0) {
        return true;
    }
    if (host[0] == '[' || strchr(host, ':') != NULL) {
        return true;
    }
    ESP_LOGW(TAG, "refused request with untrusted Host header: %s", host);
    return false;
}

/*
 * CSRF guard for state-changing POSTs: a browser names the page a form came
 * from in Origin (or at least Referer), and it has to be this device as the
 * browser addressed it (the Host header). Requests with neither header (curl,
 * scripts) pass; a page elsewhere cannot make a browser omit both.
 */
static bool same_origin(httpd_req_t *req)
{
    if (!host_allowed(req)) {
        return false;
    }
    char from[192];
    esp_err_t err = httpd_req_get_hdr_value_str(req, "Origin", from, sizeof(from));
    if (err != ESP_OK && err != ESP_ERR_HTTPD_RESULT_TRUNC) {
        err = httpd_req_get_hdr_value_str(req, "Referer", from, sizeof(from));
        if (err != ESP_OK && err != ESP_ERR_HTTPD_RESULT_TRUNC) {
            return true;
        }
    }
    char host[96];
    if (httpd_req_get_hdr_value_str(req, "Host", host, sizeof(host)) != ESP_OK ||
        !url_origin_matches_host(from, host)) {
        ESP_LOGW(TAG, "refused cross-site POST to %s from %s", req->uri, from);
        return false;
    }
    return true;
}

static esp_err_t cross_site(httpd_req_t *req)
{
    return httpd_resp_send_err(req, HTTPD_403_FORBIDDEN, "cross-site request refused");
}

/* Read a form body of at most BODY_MAX bytes into body. On failure the error reply has been sent. */
static bool read_form(httpd_req_t *req, char body[BODY_MAX + 1])
{
    if (req->content_len > BODY_MAX) {
        httpd_resp_send_err(req, HTTPD_400_BAD_REQUEST, "form too large");
        return false;
    }
    int got = 0;
    while (got < (int)req->content_len) {
        int r = httpd_req_recv(req, body + got, req->content_len - got);
        if (r <= 0) {
            httpd_resp_send_err(req, HTTPD_400_BAD_REQUEST, "read failed");
            return false;
        }
        got += r;
    }
    body[got] = '\0';
    return true;
}

/* Minimal HTML escaping for SSIDs. */
static void html_escape(const char *in, char *out, size_t out_len)
{
    size_t o = 0;
    for (; *in && o + 7 < out_len; in++) {
        const char *rep = NULL;
        switch (*in) {
        case '&': rep = "&amp;"; break;
        case '<': rep = "&lt;"; break;
        case '>': rep = "&gt;"; break;
        case '"': rep = "&quot;"; break;
        case '\'': rep = "&#39;"; break;
        default: break;
        }
        if (rep) {
            size_t l = strlen(rep);
            memcpy(out + o, rep, l);
            o += l;
        } else {
            out[o++] = *in;
        }
    }
    out[o] = '\0';
}

