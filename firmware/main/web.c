/*
 * The cached printer configuration, read again from the printer when older
 * than CFG_MAX_AGE_MS, missing, or when refresh is set. *have says whether
 * hh holds a configuration (perhaps an old one). Returns why the printer
 * could not be read, or NULL.
 */
static const char *printer_config(zpl_hh_t *hh, bool refresh, bool *have, int64_t *age_ms)
{
    *have = printer_link_get_config(hh, age_ms);
    if (!refresh && *have && *age_ms <= CFG_MAX_AGE_MS) {
        return NULL;
    }
    switch (printer_link_refresh_config(pdMS_TO_TICKS(CFG_LINK_WAIT_MS))) {
    case ESP_OK:
        *have = printer_link_get_config(hh, age_ms);
        return NULL;
    case ESP_ERR_TIMEOUT:
        return "Printer busy (printing or being detected)";
    case ESP_ERR_INVALID_STATE:
        return "Printer not detected, or holding output paused";
    case ESP_ERR_NOT_SUPPORTED:
        return "The printer is not in a ZPL language (see Language on the status page), so its settings cannot be read";
    case ESP_ERR_NO_MEM:
        return "Out of memory";
    default:
        return "No complete reply to ^HH from the printer";
    }
}

/* GET /api/printer_config[?refresh=1]: the printer's ^HH settings as [name, value] pairs. */
static esp_err_t printer_config_get(httpd_req_t *req)
{
    if (on_ap(req)) {
        return to_setup_page(req);
    }
    if (!host_allowed(req)) {
        return cross_site(req);
    }
    char q[16] = "";
    bool refresh = httpd_req_get_url_query_str(req, q, sizeof(q)) == ESP_OK && strstr(q, "refresh=1") != NULL;
    zpl_hh_t *hh = malloc(sizeof(*hh));
    if (hh == NULL) {
        return httpd_resp_send_err(req, HTTPD_500_INTERNAL_SERVER_ERROR, "out of memory");
    }
    bool have;
    int64_t age_ms = -1;
    const char *error = printer_config(hh, refresh, &have, &age_ms);
    if (!have) {
        hh->count = 0;
        age_ms = -1;
    }
    httpd_resp_set_type(req, "application/json");
    httpd_resp_set_hdr(req, "Cache-Control", "no-store");
    /* one pair at a time; each escape can grow a byte to six, so a pair always fits */
    char line[(ZPL_HH_NAME_LEN + ZPL_HH_VALUE_LEN) * 6 + 16];
    snprintf(line, sizeof(line), "{\"age_ms\":%lld,\"error\":%s%s%s,\"pairs\":[", (long long)age_ms,
             error ? "\"" : "", error ? error : "null", error ? "\"" : "");
    httpd_resp_sendstr_chunk(req, line);
    for (int i = 0; i < hh->count; i++) {
        char name[ZPL_HH_NAME_LEN * 6];
        char value[ZPL_HH_VALUE_LEN * 6];
        json_escape(hh->pair[i].name, name, sizeof(name));
        json_escape(hh->pair[i].value, value, sizeof(value));
        snprintf(line, sizeof(line), "%s[\"%s\",\"%s\"]", i ? "," : "", name, value);
        httpd_resp_sendstr_chunk(req, line);
    }
    /* the settings the printer form changes, decoded as the form's values, so the status page words them alike */
    httpd_resp_sendstr_chunk(req, "],\"cfg\":{");
    zpl_printer_cfg_t cur;
    zpl_cfg_from_hh(hh, &cur);
    free(hh);
    int k = 0;
    for (int f = 0; f < ZPL_CFG_COUNT; f++) {
        if (cur.known & (1u << f)) {
            char text[16];
            zpl_cfg_format((zpl_cfg_field_t)f, cur.v[f], text, sizeof(text));
            snprintf(line, sizeof(line), "%s\"%s\":\"%s\"", k++ ? "," : "", zpl_cfg_desc((zpl_cfg_field_t)f)->hh_name,
                     text);
            httpd_resp_sendstr_chunk(req, line);
        }
    }
    httpd_resp_sendstr_chunk(req, "}}");
    return httpd_resp_sendstr_chunk(req, NULL);
}

