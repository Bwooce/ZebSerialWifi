static esp_err_t root_get(httpd_req_t *req)
{
    if (on_ap(req)) {
        return send_setup_page(req);
    }
    if (!host_allowed(req)) {
        return cross_site(req);
    }
    httpd_resp_set_type(req, "text/html");
    httpd_resp_sendstr_chunk(req, PAGE_HEAD);
    httpd_resp_sendstr_chunk(req, STATUS_BODY);
    httpd_resp_sendstr_chunk(req, PAGE_TAIL);
    return httpd_resp_sendstr_chunk(req, NULL);
}

static esp_err_t save_post(httpd_req_t *req)
{
    if (!same_origin(req)) {
        return cross_site(req);
    }
    char body[BODY_MAX + 1];
    if (!read_form(req, body)) {
        return ESP_FAIL;
    }

    char ssid[SETTINGS_SSID_MAX] = "";
    char manual[SETTINGS_SSID_MAX] = "";
    char pass[SETTINGS_PASS_MAX] = "";
    form_get(body, "ssid", ssid, sizeof(ssid));
    form_get(body, "ssid_manual", manual, sizeof(manual));
    form_get(body, "pass", pass, sizeof(pass));
    memset(body, 0, sizeof(body));
    if (manual[0] != '\0') {
        strlcpy(ssid, manual, sizeof(ssid));
    }
    if (ssid[0] == '\0') {
        return httpd_resp_send_err(req, HTTPD_400_BAD_REQUEST, "no network chosen");
    }
    if (pass[0] != '\0' && strlen(pass) < 8) {
        return httpd_resp_send_err(req, HTTPD_400_BAD_REQUEST, "WPA passwords are at least 8 characters");
    }
    esp_err_t err = settings_set_wifi(ssid, pass);
    memset(pass, 0, sizeof(pass));
    if (err != ESP_OK) {
        return httpd_resp_send_err(req, HTTPD_500_INTERNAL_SERVER_ERROR, "could not save");
    }
    ESP_LOGI(TAG, "saved WiFi network \"%s\", rebooting", ssid);
    httpd_resp_set_type(req, "text/html");
    httpd_resp_sendstr_chunk(req, PAGE_HEAD);
    httpd_resp_sendstr_chunk(req, "<p>Saved. Rebooting and joining the network. "
                                  "Then open <a href='http://zebserial.local/'>http://zebserial.local/</a>.</p>");
    httpd_resp_sendstr_chunk(req, PAGE_TAIL);
    httpd_resp_sendstr_chunk(req, NULL);
    restart_soon();
    return ESP_OK;
}

static esp_err_t status_get(httpd_req_t *req)
{
    if (on_ap(req)) {
        return to_setup_page(req);
    }
    if (!host_allowed(req)) {
        return cross_site(req);
    }
    printer_status_t p;
    bridge_stats_t b;
    printer_link_get_status(&p);
    bridge_get_stats(&b);
    char ip[16];
    wifi_prov_ip(ip);
    /* SSIDs and printer replies can hold anything: a 32-byte SSID of control characters is 192 bytes escaped */
    char ssid_esc[32 * 6 + 1];
    json_escape(wifi_prov_ssid(), ssid_esc, sizeof(ssid_esc));
    const esp_app_desc_t *app = esp_app_get_description();
    char version_esc[sizeof(app->version) * 6];
    json_escape(app->version, version_esc, sizeof(version_esc));

    settings_net_t net;
    settings_options_t opt;
    settings_get_net(&net);
    settings_get_options(&opt);
    char handshake_esc[sizeof(p.handshake) * 6];
    json_escape(p.handshake, handshake_esc, sizeof(handshake_esc));
    char model_esc[sizeof(p.model) * 6];
    json_escape(p.model, model_esc, sizeof(model_esc));
    char lang_esc[sizeof(p.language) * 6];
    json_escape(p.language, lang_esc, sizeof(lang_esc));
    char hostname_esc[sizeof(net.hostname) * 6];
    json_escape(net.hostname, hostname_esc, sizeof(hostname_esc));
    char ip6[WIFI_PROV_IP6_MAX][46];
    int n6 = wifi_prov_ip6(ip6);
    char ip6_json[WIFI_PROV_IP6_MAX * 50 + 4] = "[";
    for (int i = 0; i < n6; i++) {
        size_t l = strlen(ip6_json);
        snprintf(ip6_json + l, sizeof(ip6_json) - l, "%s\"%s\"", i ? "," : "", ip6[i]);
    }
    strlcat(ip6_json, "]", sizeof(ip6_json));

    const size_t json_cap = 2048;
    char *json = malloc(json_cap);
    if (json == NULL) {
        return httpd_resp_send_err(req, HTTPD_500_INTERNAL_SERVER_ERROR, "out of memory");
    }
    int json_len = snprintf(json, json_cap,
             "{\"wifi\":{\"ssid\":\"%s\",\"ip\":\"%s\",\"rssi\":%d,\"hostname\":\"%s\",\"static_ip\":%s,"
             "\"ip6\":%s},"
             "\"config\":{\"target_baud\":%lu,\"pins\":%d,\"idle_timeout_s\":%u},"
             "\"printer\":{\"detected\":%s,\"answering\":%s,\"reply_age_ms\":%lld,\"model\":\"%s\","
             "\"language\":\"%s\",\"zpl\":%s,\"baud\":%lu,\"handshake\":\"%s\",\"tx_gpio\":%d,\"rx_gpio\":%d,"
             "\"hs_valid\":%s,\"hs_age_ms\":%lld,\"hs\":{\"paper_out\":%s,\"pause\":%s,\"head_up\":%s,"
             "\"ribbon_out\":%s,\"buffer_full\":%s,\"corrupt_ram\":%s,\"under_temp\":%s,\"over_temp\":%s,"
             "\"formats_in_buffer\":%d},\"tx_bytes\":%llu,\"rx_bytes\":%llu},"
             "\"bridge\":{\"active\":%s,\"client_ip\":\"%s\",\"sessions\":%lu,\"aborted\":%lu,"
             "\"to_printer\":%llu,\"from_printer\":%llu},"
             "\"uptime_s\":%lld,\"version\":\"%s\",\"built\":\"%s %s\"}",
             ssid_esc, ip, wifi_prov_rssi(), hostname_esc, net.static_ip ? "true" : "false", ip6_json,
             (unsigned long)opt.target_baud, (int)opt.pins, (unsigned)opt.idle_timeout_s, p.detected ? "true" : "false",
             p.answering ? "true" : "false", (long long)p.reply_age_ms, model_esc, lang_esc, p.zpl ? "true" : "false", (unsigned long)p.baud, handshake_esc,
             p.tx_gpio, p.rx_gpio, p.hs_valid ? "true" : "false", (long long)p.hs_age_ms,
             p.hs.paper_out ? "true" : "false", p.hs.pause ? "true" : "false", p.hs.head_up ? "true" : "false",
             p.hs.ribbon_out ? "true" : "false", p.hs.buffer_full ? "true" : "false",
             p.hs.corrupt_ram ? "true" : "false", p.hs.under_temp ? "true" : "false",
             p.hs.over_temp ? "true" : "false", p.hs.formats_in_buffer, (unsigned long long)p.tx_bytes,
             (unsigned long long)p.rx_bytes, b.active ? "true" : "false", b.client_ip, (unsigned long)b.sessions,
             (unsigned long)b.aborted, (unsigned long long)b.bytes_to_printer,
             (unsigned long long)b.bytes_from_printer, (long long)(esp_timer_get_time() / 1000000), version_esc,
             app->date, app->time);
    if (json_len < 0 || (size_t)json_len >= json_cap) {
        free(json);
        ESP_LOGE(TAG, "status JSON needs %d bytes, buffer is %u", json_len, (unsigned)json_cap);
        return httpd_resp_send_err(req, HTTPD_500_INTERNAL_SERVER_ERROR, "status too long");
    }
    httpd_resp_set_type(req, "application/json");
    httpd_resp_set_hdr(req, "Cache-Control", "no-store");
    esp_err_t err = httpd_resp_send(req, json, json_len);
    free(json);
    return err;
}

