static void ip_str(uint32_t v, char out[16])
{
    if (v == 0) {
        out[0] = '\0';
        return;
    }
    snprintf(out, 16, "%lu.%lu.%lu.%lu", (unsigned long)(v >> 24), (unsigned long)(v >> 16 & 255),
             (unsigned long)(v >> 8 & 255), (unsigned long)(v & 255));
}

